
package com.example.bookstore.service;

import com.example.bookstore.dto.ApiDtos.OrderResponse;
import com.example.bookstore.entity.AppUser;
import com.example.bookstore.entity.Book;
import com.example.bookstore.entity.Cart;
import com.example.bookstore.entity.CartItem;
import com.example.bookstore.entity.CustomerOrder;
import com.example.bookstore.entity.OrderStatus;
import com.example.bookstore.exception.NotFoundException;
import com.example.bookstore.repository.BookRepository;
import com.example.bookstore.repository.CartRepository;
import com.example.bookstore.repository.OrderRepository;
import com.example.bookstore.repository.UserRepository;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.test.util.ReflectionTestUtils;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class OrderServiceTest {

    private static final String EMAIL = "test@bookstore.com";
    private static final Long USER_ID = 1L;
    private static final Long BOOK_ID = 1L;

    @Mock
    private UserRepository userRepository;

    @Mock
    private CartRepository cartRepository;

    @Mock
    private OrderRepository orderRepository;

    @Mock
    private BookRepository bookRepository;

    @InjectMocks
    private OrderService orderService;

    private AppUser createUser() {
        AppUser user = new AppUser(
                "Test User",
                EMAIL,
                "hashed-password"
        );

        // Simulate the ID generated by the database.
        ReflectionTestUtils.setField(user, "id", USER_ID);

        return user;
    }

    private void mockUser() {
        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(createUser()));
    }

    @Test
    void checkoutShouldCreateOrderAndReduceStock() {

        AppUser user = createUser();

        Cart cart = mock(Cart.class);
        CartItem cartItem = mock(CartItem.class);
        Book book = mock(Book.class);

        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(user));

        when(cartRepository.findByUserId(USER_ID))
                .thenReturn(Optional.of(cart));

        when(cart.getItems())
                .thenReturn(List.of(cartItem));

        when(cartItem.getBook()).thenReturn(book);
        when(cartItem.getQuantity()).thenReturn(2);

        when(book.getId()).thenReturn(BOOK_ID);
        when(book.getTitle()).thenReturn("Clean Code");
        when(book.getPrice()).thenReturn(new BigDecimal("599.00"));
        when(book.getStock()).thenReturn(10);

        when(bookRepository.findByIdForUpdate(BOOK_ID))
                .thenReturn(Optional.of(book));

        when(orderRepository.save(any(CustomerOrder.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        OrderResponse response = orderService.checkout(EMAIL);

        assertNotNull(response);
        assertEquals(new BigDecimal("1198.00"), response.total());
        assertEquals(OrderStatus.PLACED, response.status());
        assertEquals(1, response.items().size());

        assertEquals("Clean Code", response.items().get(0).title());
        assertEquals(2, response.items().get(0).quantity());
        assertEquals(
                new BigDecimal("599.00"),
                response.items().get(0).unitPrice()
        );

        verify(book).decreaseStock(2);
        verify(orderRepository).save(any(CustomerOrder.class));
        verify(cart).clear();
    }

    @Test
    void checkoutShouldRejectEmptyCart() {

        AppUser user = createUser();

        Cart cart = mock(Cart.class);

        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(user));

        when(cartRepository.findByUserId(USER_ID))
                .thenReturn(Optional.of(cart));

        when(cart.getItems())
                .thenReturn(List.of());

        assertThrows(
                IllegalArgumentException.class,
                () -> orderService.checkout(EMAIL)
        );

        verifyNoInteractions(bookRepository, orderRepository);
        verify(cart, never()).clear();
    }

    @Test
    void checkoutShouldRejectInsufficientStock() {

        AppUser user = createUser();

        Cart cart = mock(Cart.class);
        CartItem cartItem = mock(CartItem.class);
        Book book = mock(Book.class);

        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(user));

        when(cartRepository.findByUserId(USER_ID))
                .thenReturn(Optional.of(cart));

        when(cart.getItems())
                .thenReturn(List.of(cartItem));

        when(cartItem.getBook()).thenReturn(book);
        when(cartItem.getQuantity()).thenReturn(5);

        when(book.getId()).thenReturn(BOOK_ID);
        when(book.getStock()).thenReturn(1);

        when(bookRepository.findByIdForUpdate(BOOK_ID))
                .thenReturn(Optional.of(book));

        assertThrows(
                IllegalArgumentException.class,
                () -> orderService.checkout(EMAIL)
        );

        verify(book, never()).decreaseStock(anyInt());
        verify(orderRepository, never()).save(any(CustomerOrder.class));
        verify(cart, never()).clear();
    }

    @Test
    void findAllShouldReturnUserOrderHistory() {

        AppUser user = createUser();

        CustomerOrder order = mock(CustomerOrder.class);

        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(user));

        when(orderRepository.findAllByUserIdOrderByCreatedAtDesc(USER_ID))
                .thenReturn(List.of(order));

        when(order.getId()).thenReturn(10L);
        when(order.getTotal()).thenReturn(new BigDecimal("1198.00"));
        when(order.getStatus()).thenReturn(OrderStatus.PLACED);
        when(order.getCreatedAt()).thenReturn(Instant.now());
        when(order.getItems()).thenReturn(List.of());

        List<OrderResponse> result = orderService.findAll(EMAIL);

        assertNotNull(result);
        assertEquals(1, result.size());
        assertEquals(10L, result.get(0).id());
        assertEquals(
                new BigDecimal("1198.00"),
                result.get(0).total()
        );
        assertEquals(OrderStatus.PLACED, result.get(0).status());

        verify(orderRepository)
                .findAllByUserIdOrderByCreatedAtDesc(USER_ID);
    }

    @Test
    void findAllShouldReturnEmptyListWhenUserHasNoOrders() {

        AppUser user = createUser();

        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(user));

        when(orderRepository.findAllByUserIdOrderByCreatedAtDesc(USER_ID))
                .thenReturn(List.of());

        List<OrderResponse> result = orderService.findAll(EMAIL);

        assertNotNull(result);
        assertTrue(result.isEmpty());

        verify(orderRepository)
                .findAllByUserIdOrderByCreatedAtDesc(USER_ID);
    }

    @Test
    void findByIdShouldReturnOrderBelongingToUser() {

        AppUser user = createUser();

        CustomerOrder order = mock(CustomerOrder.class);

        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(user));

        when(orderRepository.findByIdAndUserId(10L, USER_ID))
                .thenReturn(Optional.of(order));

        when(order.getId()).thenReturn(10L);
        when(order.getTotal()).thenReturn(new BigDecimal("599.00"));
        when(order.getStatus()).thenReturn(OrderStatus.PLACED);
        when(order.getCreatedAt()).thenReturn(Instant.now());
        when(order.getItems()).thenReturn(List.of());

        OrderResponse response = orderService.findById(EMAIL, 10L);

        assertNotNull(response);
        assertEquals(10L, response.id());
        assertEquals(
                new BigDecimal("599.00"),
                response.total()
        );

        verify(orderRepository)
                .findByIdAndUserId(10L, USER_ID);
    }

    @Test
    void findByIdShouldThrowWhenOrderDoesNotBelongToUser() {

        AppUser user = createUser();

        when(userRepository.findByEmail(EMAIL))
                .thenReturn(Optional.of(user));

        when(orderRepository.findByIdAndUserId(99L, USER_ID))
                .thenReturn(Optional.empty());

        assertThrows(
                NotFoundException.class,
                () -> orderService.findById(EMAIL, 99L)
        );

        verify(orderRepository)
                .findByIdAndUserId(99L, USER_ID);
    }
}
